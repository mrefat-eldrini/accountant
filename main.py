def ident(sqlite_sql, pg_sql): return pg_sql if is_pg() else sqlite_sql
def q(sql,p=None,one=False):
    with engine.connect() as c:
        r=c.execute(text(sql),p or {})
        if r.returns_rows:
            data=r.mappings().all()
            return (data[0] if data else None) if one else data
def execq(sql,p=None):
    with engine.begin() as c: c.execute(text(sql),p or {})
def money(v): return f"{setting('currency','AED')} {Decimal(str(v or 0)):,.2f}"
def hash_pw(pw,salt=None):
    salt=salt or secrets.token_hex(16)
    dk=hashlib.pbkdf2_hmac("sha256",pw.encode(),salt.encode(),150000)
    return f"{salt}:{dk.hex()}"
def verify_pw(pw,stored):
    try:
        salt,digest=stored.split(":",1)
        return hmac.compare_digest(hash_pw(pw,salt).split(":",1)[1],digest)
    except: return False

