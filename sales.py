    @app.post('/sales/new')
    async def create_document(request:Request):
        g=editor_guard(request)
        if g:return g
        form=await request.form()
        if not form.get('token') or not secrets.compare_digest(str(form['token']),request.session.get('sales_token','')):
            raise HTTPException(400,'This form has already been submitted or expired. Open a new document.')
        kind=form.get('kind');terms=form.get('terms')
        if kind not in ('Quotation','Sales Invoice') or terms not in ('Cash','Credit'):
            raise HTTPException(400,'Invalid document type or terms.')
        try:
            items,totals=calculate(json.loads(form.get('lines','')))
            customer_id=int(form.get('customer_id',''))
        except (ValueError,TypeError):
            raise HTTPException(400,'Invalid customer or item data.')
        customer=q('SELECT * FROM customers WHERE id=:id',{'id':customer_id},True)
        if not customer:raise HTTPException(400,'Select an existing customer.')
        when=calendar(form.get('document_date'));due=calendar(form.get('due_date'))
        if due<when:raise HTTPException(400,'Due date must not be before document date.')
        paid=cents(dec(form.get('paid',0)))
        if kind=='Quotation':paid=Decimal(0)
        elif terms=='Cash':paid=totals['total']
        if paid>totals['total']:raise HTTPException(400,'Payment cannot exceed document total.')
        prefix='QT' if kind=='Quotation' else 'SI'
        payload=dict(document_no=prefix+'-'+date.today().strftime('%y%m%d')+'-'+secrets.token_hex(3).upper(),
                     kind=kind,customer_id=customer_id,customer_name=customer['name'],document_date=when,due_date=due,
                     terms=terms,currency=setting('currency','AED'),items_json=json.dumps(items,ensure_ascii=False),
                     **{k:str(v) for k,v in totals.items()},notes=str(form.get('notes',''))[:2000],
                     invoice_id=None,source_id=None,converted_id=None,created_by=user(request)['username'])
        with engine.begin() as conn:
            if kind=='Sales Invoice':payload['invoice_id']=post_invoice(conn,payload,paid)
            doc_id=insert_document(conn,payload)
            payment(conn,doc_id,paid,when,'Cash' if terms=='Cash' else 'Bank Transfer')
        request.session.pop('sales_token',None)
        audit(request,'CREATE_SALES_DOCUMENT','Sales',payload['document_no'],kind)
        return RedirectResponse(f'/sales/{doc_id}',303)

    @app.get('/sales/reports',response_class=HTMLResponse)
    def sales_reports(request:Request):
        g=guard(request)
        if g:return g
        start=request.query_params.get('from','');end=request.query_params.get('to','')
        conditions=["kind!='Quotation'"];params={}
        if start:conditions.append('document_date>=:start');params['start']=calendar(start)
        if end:conditions.append('document_date<=:end');params['end']=calendar(end)
        if start and end and start>end:raise HTTPException(400,'Invalid date range.')
        rows=q('SELECT * FROM sales_documents WHERE '+' AND '.join(conditions)+' ORDER BY document_date DESC,id DESC',params)
        if request.query_params.get('format')=='csv':
            out=StringIO();writer=csv.writer(out);writer.writerow(['Document','Type','Customer','Date','Currency','Subtotal','Tax','Total'])
