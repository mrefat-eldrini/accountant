CENT = Decimal('0.01')


def dec(value, minimum=Decimal('0'), maximum=Decimal('100000000')):
    try:
        result = Decimal(str(value))
        if not result.is_finite() or not minimum <= result <= maximum:
            raise ValueError()
        return result
    except (InvalidOperation, ValueError, TypeError):
        raise HTTPException(400, 'Invalid numeric value.')


def cents(value):
    return value.quantize(CENT, rounding=ROUND_HALF_UP)


def clean(value, limit=500):
    value = str(value).strip()
    if not value or len(value) > limit:
        raise HTTPException(400, 'A required field is missing or too long.')
    return value


def calendar(value):
    try:
        return date.fromisoformat(str(value)).isoformat()
    except ValueError:
        raise HTTPException(400, 'Invalid date.')


def calculate(lines):
    if not isinstance(lines, list) or not 1 <= len(lines) <= 100:
        raise HTTPException(400, 'Enter between 1 and 100 items.')
    items = []
    for row in lines:
        if not isinstance(row, dict):
            raise HTTPException(400, 'Invalid item.')
        quantity = dec(row.get('quantity'), Decimal('0.001'), Decimal('100000'))
        if quantity != quantity.quantize(Decimal('0.001')):
            raise HTTPException(400, 'Quantity supports up to three decimal places.')
        price = cents(dec(row.get('price'), maximum=Decimal('1000000')))
        discount_rate = dec(row.get('discount', 0), maximum=Decimal('100'))
        tax_rate = dec(row.get('tax_rate', 0), maximum=Decimal('100'))
        gross = cents(quantity * price)
        discount = cents(gross * discount_rate / 100)
        subtotal = gross - discount
        tax = cents(subtotal * tax_rate / 100)
        items.append(dict(code=str(row.get('code', ''))[:80], description=clean(row.get('description', '')),
                          unit=clean(row.get('unit', 'pcs'), 30), quantity=str(quantity), price=str(price),
                          discount_rate=str(discount_rate), tax_rate=str(tax_rate),
                          discount=str(discount), subtotal=str(subtotal), tax=str(tax), total=str(subtotal+tax)))
    totals = {key: sum((Decimal(item[key]) for item in items), Decimal(0))
              for key in ('discount', 'subtotal', 'tax', 'total')}
    if totals['total'] > Decimal('100000000'):
        raise HTTPException(400, 'Document total is too large.')
    return items, totals


def init_sales(engine, pg):
    identity = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if pg else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    with engine.begin() as conn:
        conn.execute(text(f'''CREATE TABLE IF NOT EXISTS sales_documents (
            id {identity}, document_no TEXT UNIQUE NOT NULL, kind TEXT NOT NULL,
            customer_id INTEGER NOT NULL, customer_name TEXT NOT NULL, document_date TEXT NOT NULL,
            due_date TEXT NOT NULL, terms TEXT NOT NULL, currency TEXT NOT NULL,
            items_json TEXT NOT NULL, subtotal NUMERIC NOT NULL, tax NUMERIC NOT NULL,
            total NUMERIC NOT NULL, discount NUMERIC NOT NULL, notes TEXT NOT NULL,
            invoice_id INTEGER, source_id INTEGER, converted_id INTEGER, created_by TEXT NOT NULL)'''))
        conn.execute(text(f'''CREATE TABLE IF NOT EXISTS sales_payments (
            id {identity}, document_id INTEGER NOT NULL, payment_date TEXT NOT NULL,
            amount NUMERIC NOT NULL, method TEXT NOT NULL, reference TEXT NOT NULL)'''))
        conn.execute(text('CREATE INDEX IF NOT EXISTS sales_source_idx ON sales_documents(source_id)'))


