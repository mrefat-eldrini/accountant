        body=f"<div class='card'><p class='muted'>Sales documents only</p><form class='gridform'><label class='sales-label'><span>From</span><input type='date' name='from' value='{escape(start)}'></label><label class='sales-label'><span>To</span><input type='date' name='to' value='{escape(end)}'></label><button>Apply filters</button><a class='btn' href='{escape(export,quote=True)}'>Export CSV</a></form><div class='sales-summary'><span>Sales before tax</span><strong>{amount(total)}</strong><span>VAT</span><strong>{amount(tax)}</strong><span>Net sales</span><strong>{amount(total+tax)}</strong></div>{listing(rows)}</div>"
