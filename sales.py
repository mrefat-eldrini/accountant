    @app.post('/sales/{doc_id}/payment')
    async def record_payment(request:Request,doc_id:int):
        g=editor_guard(request)
        if g:return g
        form=await action_form(request);paid=cents(dec(form.get('amount'),Decimal('.01')))
        when=calendar(form.get('payment_date'));method=form.get('method')
        if method not in ('Cash','Bank Transfer','Card'):raise HTTPException(400,'Invalid payment method.')
        with engine.begin() as conn:
            doc=get_doc(doc_id,conn,True)
            if doc['kind']!='Sales Invoice':raise HTTPException(400,'Only invoices accept payments.')
            inv=conn.execute(text('SELECT * FROM invoices WHERE id=:id'),{'id':doc['invoice_id']}).mappings().one()
            if paid>Decimal(str(inv['total']))-Decimal(str(inv['paid'])):raise HTTPException(400,'Payment exceeds outstanding balance.')
            new_paid=Decimal(str(inv['paid']))+paid
            status='Paid' if new_paid==Decimal(str(inv['total'])) else 'Partially Paid'
            conn.execute(text('UPDATE invoices SET paid=:paid,status=:status WHERE id=:id'),{'paid':str(new_paid),'status':status,'id':doc['invoice_id']})
            payment(conn,doc_id,paid,when,method,str(form.get('reference',''))[:100])
        request.session.pop('sales_action_token',None)
        audit(request,'RECORD_SALES_PAYMENT','Sales',doc['document_no'],str(paid))
        return RedirectResponse(f'/sales/{doc_id}',303)

    @app.post('/sales/{doc_id}/return')
    async def sales_return(request:Request,doc_id:int):
        g=editor_guard(request)
        if g:return g
        form=await action_form(request);reason=clean(form.get('reason',''))
        with engine.begin() as conn:
            doc=dict(get_doc(doc_id,conn,True))
            if doc['kind']!='Sales Invoice':raise HTTPException(400,'Returns require an original sales invoice.')
            items=json.loads(doc['items_json'])
            credits=conn.execute(text("SELECT items_json FROM sales_documents WHERE source_id=:id AND kind='Credit Note'"),{'id':doc_id}).mappings().all()
            previous={}
            for credit in credits:
                for line in json.loads(credit['items_json']):
                    key=line['line_index']
                    if key not in previous:previous[key]={k:Decimal(0) for k in ('quantity','discount','subtotal','tax','total')}
                    for k in previous[key]:previous[key][k]+=Decimal(line[k])
            returned=[]
            for index,line in enumerate(items):
                quantity=dec(form.get(f'return_{index}',0),maximum=Decimal('100000'))
                if not quantity:continue
                if quantity!=quantity.quantize(Decimal('.001')):raise HTTPException(400,'Invalid quantity precision.')
                used=previous.get(index,{k:Decimal(0) for k in ('quantity','discount','subtotal','tax','total')})
                remaining=Decimal(line['quantity'])-used['quantity']
                if quantity>remaining:raise HTTPException(400,'Return exceeds remaining item quantity.')
                returned_line=dict(line,quantity=str(quantity),line_index=index)
                for key in ('discount','subtotal','tax'):
                    # Cumulative rounding guarantees partial returns never exceed original money.
                    target=cents(Decimal(line[key])*(used['quantity']+quantity)/Decimal(line['quantity']))
                    returned_line[key]=str(target-used[key])
                returned_line['total']=str(Decimal(returned_line['subtotal'])+Decimal(returned_line['tax']))
                returned.append(returned_line)
            if not returned:raise HTTPException(400,'Enter at least one return quantity.')
            totals={key:sum((Decimal(line[key]) for line in returned),Decimal(0)) for key in ('discount','subtotal','tax','total')}
            payload={k:v for k,v in doc.items() if k!='id'}
            payload.update(document_no='CN-'+secrets.token_hex(5).upper(),kind='Credit Note',source_id=doc_id,converted_id=None,
                           document_date=str(date.today()),items_json=json.dumps(returned,ensure_ascii=False),notes=reason,
                           **{k:str(v) for k,v in totals.items()},created_by=user(request)['username'])
            credit_id=insert_document(conn,payload)
            inv=conn.execute(text('SELECT * FROM invoices WHERE id=:id'),{'id':doc['invoice_id']}).mappings().one()
            net=cents(Decimal(str(inv['total']))-totals['total'])
            refund=max(Decimal(str(inv['paid']))-net,Decimal(0));paid=min(Decimal(str(inv['paid'])),net)
            status='Paid' if paid==net else ('Partially Paid' if paid else 'Unpaid')
            conn.execute(text('''UPDATE invoices SET total=:total,subtotal=:sub,tax=:tax,paid=:paid,status=:status WHERE id=:id'''),
                {'total':str(net),'sub':str(Decimal(str(inv['subtotal']))-totals['subtotal']),
                 'tax':str(Decimal(str(inv['tax']))-totals['tax']),'paid':str(paid),'status':status,'id':doc['invoice_id']})
            conn.execute(text('''INSERT INTO transactions(txn_date,description,category,txn_type,amount,tax,reference,account_code)
                VALUES(:date,:description,'Sales return','income',:amount,:tax,:ref,'4000')'''),
                {'date':str(date.today()),'description':'Sales return '+payload['document_no'],
                 'amount':str(-totals['subtotal']),'tax':str(-totals['tax']),'ref':payload['document_no']})
            payment(conn,doc_id,-refund,str(date.today()),'Refund pending',payload['document_no'])
        request.session.pop('sales_action_token',None)
        audit(request,'CREATE_SALES_RETURN','Sales',payload['document_no'],doc['document_no'])
        return RedirectResponse(f'/sales/{credit_id}',303)

