    def get_doc(doc_id, conn=None, lock=False):
        sql = 'SELECT * FROM sales_documents WHERE id=:id'
        if lock and ctx['is_pg']():
            sql += ' FOR UPDATE'
        row = conn.execute(text(sql), {'id':doc_id}).mappings().first() if conn else q(sql, {'id':doc_id}, True)
        if not row:
            raise HTTPException(404, 'Document not found.')
        return row

    def insert_document(conn, payload):
        cols = ','.join(payload)
        vals = ','.join(':'+key for key in payload)
        return conn.execute(text(f'INSERT INTO sales_documents ({cols}) VALUES ({vals}) RETURNING id'), payload).scalar_one()

    def post_invoice(conn, payload, paid):
        total = Decimal(str(payload['total']))
        status = 'Paid' if paid >= total else ('Partially Paid' if paid > 0 else 'Unpaid')
        inv_id = conn.execute(text('''INSERT INTO invoices(invoice_no,customer_name,issue_date,due_date,status,subtotal,tax,total,paid,notes)
            VALUES(:document_no,:customer_name,:document_date,:due_date,:status,:subtotal,:tax,:total,:paid,:notes) RETURNING id'''),
            dict(payload, paid=str(paid), status=status)).scalar_one()
        conn.execute(text('''INSERT INTO transactions(txn_date,description,category,txn_type,amount,tax,reference,account_code)
            VALUES(:document_date,:description,'Sales','income',:subtotal,:tax,:document_no,'4000')'''),
            dict(payload,description='Sales invoice '+payload['document_no']))
        return inv_id

    def payment(conn, document_id, paid, when, method, reference=''):
        if paid:
            conn.execute(text('''INSERT INTO sales_payments(document_id,payment_date,amount,method,reference)
                VALUES(:doc,:date,:amount,:method,:reference)'''),
                {'doc':document_id,'date':when,'amount':str(paid),'method':method,'reference':reference})

